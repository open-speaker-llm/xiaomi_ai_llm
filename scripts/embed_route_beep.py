#!/usr/bin/env python3
"""Generate the S28 cue as raw PCM or embed it in the packaged client."""
import argparse
import math
import struct
from pathlib import Path

CLIENT = Path(__file__).resolve().parents[1] / "device/native_first_client.sh"
BEGIN = "# BEGIN GENERATED ROUTE BEEP"
END = "# END GENERATED ROUTE BEEP"
RATE = 24000
PERIOD = RATE // 2000
FADE = RATE * 8 // 1000
TONE = RATE * 120 // 1000
ATTACK = RATE * 12 // 1000
GAP = RATE * 90 // 1000
PEAK = 10 ** (-3 / 20)
SUSTAIN = 0.19


def pcm(start, stop):
    samples = []
    for i in range(start, stop):
        # Preserve the short -3 dBFS attack and calibrate the sustained RMS.
        fade_in = min(1, i / FADE)
        fade_out = min(1, (TONE - 1 - i) / FADE)
        decay = min(1, max(0, (i - FADE - PERIOD) / (ATTACK - FADE - PERIOD)))
        amplitude = SUSTAIN + (PEAK - SUSTAIN) * (1 + math.cos(math.pi * decay)) / 2
        envelope = (1 - math.cos(math.pi * fade_in)) * (1 - math.cos(math.pi * fade_out)) / 4
        sample = round(amplitude * 32767 * envelope * math.sin(2 * math.pi * (i % PERIOD) / PERIOD))
        samples.append(sample)
    return struct.pack(f"<{len(samples)}h", *samples)


def shell():
    def emit(data):
        escaped = "".join(f"\\{byte:03o}" for byte in data)
        return f"printf '{escaped}' || return 1"

    block_samples = RATE // 100
    middle = emit(pcm(ATTACK, ATTACK + PERIOD) * (block_samples // PERIOD))
    middle_blocks = (TONE - ATTACK - FADE) // block_samples
    gap = emit(bytes(GAP * 2 // 9))
    return f"""{BEGIN}
# Generated by scripts/embed_route_beep.py. Repeated PCM blocks are byte-identical.
route_beep_default_pcm() {{
    local tone=0 block
    while [ "$tone" -lt 2 ]; do
        {emit(pcm(0, ATTACK))}
        block=0
        while [ "$block" -lt {middle_blocks} ]; do
            {middle}
            block=$((block + 1))
        done
        {emit(pcm(TONE - FADE, TONE))}
        tone=$((tone + 1))
        [ "$tone" -lt 2 ] || break
        block=0
        while [ "$block" -lt 9 ]; do
            {gap}
            block=$((block + 1))
        done
    done
}}
{END}"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--pcm", type=Path, metavar="FILE")
    args = parser.parse_args()
    if args.pcm:
        tone = pcm(0, TONE)
        args.pcm.write_bytes(tone + bytes(GAP * 2) + tone)
        return
    source = CLIENT.read_text()
    start, end = source.index(BEGIN), source.index(END) + len(END)
    generated = source[:start] + shell() + source[end:]
    if args.check:
        if generated != source:
            parser.exit(1, "Route beep PCM embed is stale.\n")
        print("Route beep PCM embed is current.")
    else:
        CLIENT.write_text(generated)


if __name__ == "__main__":
    main()
