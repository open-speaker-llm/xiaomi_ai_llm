#!/usr/bin/env python3
"""Export the default route cue or embed it in the packaged client."""
import argparse
import struct
from pathlib import Path

from generate_dongdong import ASSETS, NAME, dongdong_pcm, dongdong_wav

CLIENT = Path(__file__).resolve().parents[1] / "device/native_first_client.sh"
BEGIN = "# BEGIN GENERATED ROUTE BEEP"
END = "# END GENERATED ROUTE BEEP"


def shell(pcm):
    def emit(data):
        lines = []
        # Keep each BusyBox printf short. No asset or decoder is needed at install time.
        for start in range(0, len(data), 480):
            chunk = data[start:start + 480]
            escaped = "".join(f"\\{byte:03o}" for byte in chunk)
            lines.append(f"        printf '{escaped}' || return 1")
        return lines

    half_gain = struct.pack(f"<{len(pcm) // 2}h",
                            *(int(sample / 2) for sample, in struct.iter_unpack("<h", pcm)))
    return "\n".join([BEGIN, "# Generated by scripts/embed_route_beep.py.",
                      "route_beep_default_pcm() {", '    if [ "${1:-}" = calibrated ]; then',
                      *emit(half_gain), "    else", *emit(pcm), "    fi", "}", END])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--pcm", type=Path, metavar="FILE")
    args = parser.parse_args()
    pcm = dongdong_pcm()
    if args.pcm:
        args.pcm.write_bytes(pcm)
        return
    source = CLIENT.read_text()
    start, end = source.index(BEGIN), source.index(END) + len(END)
    generated = source[:start] + shell(pcm) + source[end:]
    if args.check:
        if ((ASSETS / f"{NAME}.pcm").read_bytes() != pcm or
                (ASSETS / f"{NAME}.wav").read_bytes() != dongdong_wav(pcm)):
            parser.exit(1, "Route beep assets are stale. Run scripts/generate_dongdong.py.\n")
        if generated != source:
            parser.exit(1, "Route beep PCM embed is stale.\n")
        print("Route beep assets and PCM embed are current.")
    else:
        CLIENT.write_text(generated)


if __name__ == "__main__":
    main()
